"""±20% weight-sensitivity check for the recommender (PROJECT_PLAN §6, Task A4).

Run:  python -m eval.sensitivity   → rewrites eval/SENSITIVITY.md
Each formula weight is scaled by 0.8 and 1.2, one at a time, for Aina (synthetic) at intake and
after the golden-journey events, in both scenarios. The report says whether the top role changes.
"""

import json
from pathlib import Path

from src.contract import SCENARIOS, Profile
from src.engine.catalogue import default_catalogue
from src.engine.recommend import top_role_under_sensitivity
from src.engine.skills import derive_states
from tests.helpers import golden_journey_events

DELTA = 0.20
ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "eval" / "SENSITIVITY.md"


def build_report() -> str:
    cat = default_catalogue()
    profile = Profile.model_validate(
        json.loads((ROOT / "schemas" / "examples" / "profile.json").read_text(encoding="utf-8"))
    )
    confidence = {s.skill_id: s.confidence for s in profile.skills_self_reported}
    lines = [
        "# Recommender weight sensitivity (±20%)",
        "",
        "Generated by `python -m eval.sensitivity`. Persona: Aina (synthetic). Assumptions v1.",
        "Each weight of `0.55*coverage + 0.20*confidence + 0.10*interest - 0.15*effort` is scaled",
        "by 0.8 or 1.2, one at a time; the table shows the top-ranked role.",
        "",
        "| Evidence | Scenario | Baseline top role | Variations that change it |",
        "|---|---|---|---|",
    ]
    for label, events in (("intake only", []), ("after golden journey", golden_journey_events())):
        states = derive_states(profile.id, list(cat.skills), events, confidence)
        for scenario in SCENARIOS:
            report = top_role_under_sensitivity(
                profile, states, cat, cat.assumptions_v1, scenario, DELTA
            )
            base = report.pop("baseline")
            flips = [f"{k} → {v}" for k, v in report.items() if v != base] or ["none (stable)"]
            lines.append(f"| {label} | {scenario} | {base} | {'; '.join(flips)} |")
    lines += [
        "",
        "Reading: a row with flips means the top two roles are close (often a near tie between",
        "interest and effort); the UI should present such rankings as weak, not as a verdict.",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(build_report(), encoding="utf-8")
    print(f"wrote {OUTPUT}")
