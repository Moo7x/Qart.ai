"""Write web/src/apiTypes.ts: TypeScript types for every typed API answer, from the OpenAPI schema.

Run: python -m scripts.api_types   (tests/test_api_types.py fails when the file is out of date)

The schema comes from the app itself (FastAPI builds it from the response models), so the web
app's types follow the server's and a contract change without regeneration fails the tests.
Only the JSON Schema shapes pydantic emits are handled: objects, arrays, enums and constants,
nullable unions, maps and references.
"""

import json
from typing import Any

from src.app import create_app
from src.config import REPO_ROOT, Settings

OUT = REPO_ROOT / "web" / "src" / "apiTypes.ts"
HEADER = (
    "// Generated by `python -m scripts.api_types` from the API's OpenAPI schema. Do not edit.\n"
    "/* eslint-disable */\n"
)
SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}


def _ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(_ts(s) for s in schema[key]))
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "array":
        item = _ts(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        if "properties" in schema:
            return _object(schema)
        values = schema.get("additionalProperties")
        return f"Record<string, {_ts(values) if isinstance(values, dict) else 'unknown'}>"
    return SCALARS.get(str(kind), "unknown")


def _object(schema: dict[str, Any]) -> str:
    # An answer always carries every field except one that defaults to None, which may be left
    # out (answers built with exclude_unset, e.g. AI-basics stops on /tracks). Fields with a
    # default factory carry no "default" in the schema, so this is read from the default itself.
    optional = {
        name
        for name, prop in schema["properties"].items()
        if "default" in prop and prop["default"] is None
    }
    required = set(schema["properties"]) - optional
    fields = [
        f"  {name}{'' if name in required else '?'}: {_ts(prop)}"
        for name, prop in schema["properties"].items()
    ]
    return "{\n" + "\n".join(fields) + "\n}"


def _refs(schema: Any) -> set[str]:
    if isinstance(schema, dict):
        found = {str(schema["$ref"]).rsplit("/", 1)[-1]} if "$ref" in schema else set()
        return found.union(*(_refs(v) for v in schema.values()))
    if isinstance(schema, list):
        return set().union(*(_refs(v) for v in schema))
    return set()


def answer_schemas(openapi: dict[str, Any]) -> set[str]:
    """The models reachable from a successful answer (request bodies are left out: their
    defaults mean "may be omitted", which is not what an answer's defaults mean)."""
    schemas = openapi["components"]["schemas"]
    todo = {
        name
        for path in openapi["paths"].values()
        for op in path.values()
        for code, response in op.get("responses", {}).items()
        if code.startswith("2")
        for name in _refs(response)
    }
    seen: set[str] = set()
    while todo:
        name = todo.pop()
        if name not in seen:
            seen.add(name)
            todo |= _refs(schemas[name]) - seen
    return seen


def render(openapi: dict[str, Any]) -> str:
    schemas = openapi["components"]["schemas"]
    parts = [HEADER]
    for name in sorted(answer_schemas(openapi)):
        parts.append(f"export type {name} = {_ts(schemas[name])}\n")
    return "\n".join(parts)


def generate() -> str:
    settings = Settings(
        database_url="sqlite://",
        llm_api_key=None,
        llm_base_url=None,
        llm_model="gpt-4.1-mini",
        runpod_api_key=None,
        runpod_endpoint_id=None,
        admin_token=None,
    )
    return render(create_app(settings, first_run=False).openapi())


def main() -> None:
    OUT.write_text(generate(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
