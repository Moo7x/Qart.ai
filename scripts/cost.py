"""Cost per person and per month, from measured usage (docs/PHASE2_PLAN.md A9).

    python scripts/cost.py            # uses DATABASE_URL (Replit) or the local SQLite file

Measured: every language-model and GPU call the app made (src/usage.py), its tokens and seconds,
and the number of profiles created in the same period. Estimated: cost = measured usage ×
declared prices (src/params.py), then per person = cost ÷ profiles, and per month at 1,000 and
10,000 people = per person × people. Measured and projected values are kept in separate tables
in docs/COST.md. Hosting is listed separately because it does not grow per person.
"""

import sys
from pathlib import Path
from typing import Any

from sqlalchemy import func, select

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import params, usage  # noqa: E402
from src.api.status import cost_rows  # noqa: E402
from src.config import REPO_ROOT, load_settings  # noqa: E402
from src.db import make_engine  # noqa: E402
from src.envfile import load_env_file  # noqa: E402
from src.journey.store import profile_table  # noqa: E402

OUT = REPO_ROOT / "docs" / "COST.md"
PEOPLE = (1_000, 10_000)


def _row(r: dict[str, Any]) -> str:
    cost = "price not set" if r["cost_usd"] is None else f"{r['cost_usd']:.4f}"
    tokens = f"{r['tokens_in']} / {r['tokens_out']}"
    return (
        f"| {r['purpose']} | {r['model']} | {r['calls']} | {tokens} | {r['seconds']:.1f} | {cost} |"
    )


def main() -> None:
    load_env_file()
    engine = make_engine(load_settings().database_url)
    rows = cost_rows(usage.totals(engine))
    with engine.connect() as conn:
        first, profiles = conn.execute(select(func.min(usage.usage_table.c.at), func.count())).one()
        people = conn.execute(select(func.count()).select_from(profile_table)).scalar_one()
    known = sum(r["cost_usd"] or 0 for r in rows)
    gpu_seconds = sum(r["seconds"] for r in rows if r["engine"] == "runpod")
    per_person = known / people if people else None
    lines = [
        "# Cost: measured usage and projection",
        "",
        f"Generated by `python scripts/cost.py`. Prices: {params.PRICES_CHECKED} list prices "
        "(src/params.py); check the providers before quoting. Usage counted since "
        f"{first or 'no calls yet'}; {people} profiles exist now (profiles deleted after "
        f"{params.PROFILE_RETENTION_DAYS} idle days are not counted).",
        "",
        "## Measured",
        "",
        "| Purpose | Model | Calls | Tokens in / out | Seconds | Cost (USD, estimate) |",
        "|---|---|---|---|---|---|",
        *(_row(r) for r in rows),
        "",
        f"Language-model cost so far: USD {known:.4f}. GPU time so far: {gpu_seconds:.0f} s"
        + ("" if params.RUNPOD_USD_PER_SECOND else " (price per second not set yet)."),
        "",
        "## Projected (estimate)",
        "",
        "| People per month | Language-model cost (USD) |",
        "|---|---|",
        *(
            f"| {n:,} | {'not enough data' if per_person is None else f'{per_person * n:.2f}'} |"
            for n in PEOPLE
        ),
        "",
        "Per person = measured cost ÷ profiles. It assumes future people use the app as the "
        "measured ones did; the load test's people read CVs less often than real users would.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[-8:]))
    _ = profiles


if __name__ == "__main__":
    main()
